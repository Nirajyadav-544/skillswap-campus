package com.skillswap.resume.dto;

import com.skillswap.resume.entity.ResumeAnalysis;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

public class ResumeAnalysisResponse {

    private Long id;
    private Long resumeId;

    private Double overallScore;
    private Double atsScore;
    private Double skillsScore;
    private Double experienceScore;
    private Double educationScore;

    private String strengths;
    private String weaknesses;
    private String recommendations;
    private String analysisText;

    private LocalDateTime createdAt;

    /*
     * Resume analysis details generated by ResumeAnalysisService
     */
    private String targetCareer;

    private List<String> detectedSkills;
    private List<String> skillGaps;
    private List<String> missingKeywords;

    private List<String> formattingSuggestions;
    private List<String> improvementSuggestions;

    private double careerMatchPercentage;

    private String message;

    public ResumeAnalysisResponse() {
        this.detectedSkills = new ArrayList<>();
        this.skillGaps = new ArrayList<>();
        this.missingKeywords = new ArrayList<>();
        this.formattingSuggestions = new ArrayList<>();
        this.improvementSuggestions = new ArrayList<>();
    }

    /**
     * Converts persisted ResumeAnalysis entity into API response.
     */
    public static ResumeAnalysisResponse from(
            ResumeAnalysis analysis
    ) {

        if (analysis == null) {
            return null;
        }

        ResumeAnalysisResponse response =
                new ResumeAnalysisResponse();

        response.setId(
                analysis.getId()
        );

        if (analysis.getResume() != null) {
            response.setResumeId(
                    analysis.getResume().getId()
            );
        }

        response.setOverallScore(
                analysis.getOverallScore()
        );

        response.setAtsScore(
                analysis.getAtsScore()
        );

        response.setSkillsScore(
                analysis.getSkillsScore()
        );

        response.setExperienceScore(
                analysis.getExperienceScore()
        );

        response.setEducationScore(
                analysis.getEducationScore()
        );

        response.setStrengths(
                analysis.getStrengths()
        );

        response.setWeaknesses(
                analysis.getWeaknesses()
        );

        response.setRecommendations(
                analysis.getRecommendations()
        );

        response.setAnalysisText(
                analysis.getAnalysisText()
        );

        response.setCreatedAt(
                analysis.getCreatedAt()
        );

        return response;
    }

    /**
     * Creates a successful analysis response.
     */
    public static ResumeAnalysisResponse success(
            String message
    ) {

        ResumeAnalysisResponse response =
                new ResumeAnalysisResponse();

        response.setMessage(message);

        return response;
    }

    // =========================================================
    // BASIC ANALYSIS FIELDS
    // =========================================================

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getResumeId() {
        return resumeId;
    }

    public void setResumeId(Long resumeId) {
        this.resumeId = resumeId;
    }

    public Double getOverallScore() {
        return overallScore;
    }

    public void setOverallScore(Double overallScore) {
        this.overallScore = overallScore;
    }

    public Double getAtsScore() {
        return atsScore;
    }

    public void setAtsScore(Double atsScore) {
        this.atsScore = atsScore;
    }

    public Double getSkillsScore() {
        return skillsScore;
    }

    public void setSkillsScore(Double skillsScore) {
        this.skillsScore = skillsScore;
    }

    public Double getExperienceScore() {
        return experienceScore;
    }

    public void setExperienceScore(Double experienceScore) {
        this.experienceScore = experienceScore;
    }

    public Double getEducationScore() {
        return educationScore;
    }

    public void setEducationScore(Double educationScore) {
        this.educationScore = educationScore;
    }

    // =========================================================
    // TEXT ANALYSIS FIELDS
    // =========================================================

    public String getStrengths() {
        return strengths;
    }

    public void setStrengths(String strengths) {
        this.strengths = strengths;
    }

    public String getWeaknesses() {
        return weaknesses;
    }

    public void setWeaknesses(String weaknesses) {
        this.weaknesses = weaknesses;
    }

    public String getRecommendations() {
        return recommendations;
    }

    public void setRecommendations(String recommendations) {
        this.recommendations = recommendations;
    }

    public String getAnalysisText() {
        return analysisText;
    }

    public void setAnalysisText(String analysisText) {
        this.analysisText = analysisText;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    // =========================================================
    // RESUME ANALYSIS SERVICE FIELDS
    // =========================================================

    public String getTargetCareer() {
        return targetCareer;
    }

    public void setTargetCareer(String targetCareer) {
        this.targetCareer = targetCareer;
    }

    public List<String> getDetectedSkills() {
        return detectedSkills;
    }

    public void setDetectedSkills(
            List<String> detectedSkills
    ) {

        this.detectedSkills =
                detectedSkills != null
                        ? new ArrayList<>(detectedSkills)
                        : new ArrayList<>();
    }

    public List<String> getSkillGaps() {
        return skillGaps;
    }

    public void setSkillGaps(
            List<String> skillGaps
    ) {

        this.skillGaps =
                skillGaps != null
                        ? new ArrayList<>(skillGaps)
                        : new ArrayList<>();
    }

    public List<String> getMissingKeywords() {
        return missingKeywords;
    }

    public void setMissingKeywords(
            List<String> missingKeywords
    ) {

        this.missingKeywords =
                missingKeywords != null
                        ? new ArrayList<>(missingKeywords)
                        : new ArrayList<>();
    }

    public List<String> getFormattingSuggestions() {
        return formattingSuggestions;
    }

    public void setFormattingSuggestions(
            List<String> formattingSuggestions
    ) {

        this.formattingSuggestions =
                formattingSuggestions != null
                        ? new ArrayList<>(formattingSuggestions)
                        : new ArrayList<>();
    }

    public List<String> getImprovementSuggestions() {
        return improvementSuggestions;
    }

    public void setImprovementSuggestions(
            List<String> improvementSuggestions
    ) {

        this.improvementSuggestions =
                improvementSuggestions != null
                        ? new ArrayList<>(improvementSuggestions)
                        : new ArrayList<>();
    }

    public double getCareerMatchPercentage() {
        return careerMatchPercentage;
    }

    public void setCareerMatchPercentage(
            double careerMatchPercentage
    ) {

        this.careerMatchPercentage =
                careerMatchPercentage;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }
}