package com.skillswap.session.service;

import com.skillswap.common.exception.BadRequestException;
import com.skillswap.common.exception.ResourceNotFoundException;
import com.skillswap.exchange.entity.ExchangeRequest;
import com.skillswap.exchange.entity.ExchangeStatus;
import com.skillswap.exchange.repository.ExchangeRequestRepository;
import com.skillswap.identity.entity.User;
import com.skillswap.identity.repository.UserRepository;
import com.skillswap.session.dto.CreateSessionRequest;
import com.skillswap.session.dto.SessionPageResponse;
import com.skillswap.session.dto.SessionResponse;
import com.skillswap.session.dto.UpdateSessionRequest;
import com.skillswap.session.entity.LearningSession;
import com.skillswap.session.entity.SessionStatus;
import com.skillswap.session.repository.LearningSessionRepository;
