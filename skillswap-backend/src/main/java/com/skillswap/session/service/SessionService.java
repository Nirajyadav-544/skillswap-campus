import java.util.UUID;

@Service
@Transactional
public class SessionService {

    private final LearningSessionRepository sessionRepository;
    private final ExchangeRequestRepository exchangeRequestRepository;
    private final UserRepository userRepository;

    public SessionService(
            LearningSessionRepository sessionRepository,
            ExchangeRequestRepository exchangeRequestRepository,
            UserRepository userRepository
    ) {
        this.sessionRepository = sessionRepository;
        this.exchangeRequestRepository = exchangeRequestRepository;
        this.userRepository = userRepository;
    }

    /**
     * Creates a learning session for an accepted exchange.
     *
     * Only the teacher is allowed to schedule the session.
     * The meeting URL is generated by the backend.
     */
    public SessionResponse create(
            CreateSessionRequest request,
            String userEmail
    ) {

        if (request == null) {
            throw new BadRequestException(
                    "Session request is required"
            );
        }

        request.normalize();

        if (userEmail == null || userEmail.isBlank()) {
            throw new BadRequestException(
                    "Authenticated user is required"
            );
        }

        if (!request.hasValidSchedule()) {
            throw new BadRequestException(
                    "Scheduled end must be after scheduled start"
            );
        }

        User currentUser = getUser(userEmail);

        ExchangeRequest exchangeRequest =
                exchangeRequestRepository
                        .findById(request.getExchangeRequestId())
                        .orElseThrow(() ->
                                new ResourceNotFoundException(
                                        "Exchange request not found"
                                )
                        );

        validateExchangeForSession(
                exchangeRequest,
                currentUser
        );

        User teacher =
                userRepository
                        .findById(request.getTeacherUserId())
                        .orElseThrow(() ->
                                new ResourceNotFoundException(
                                        "Teacher user not found"
                                )
                        );

        User learner =
                userRepository
                        .findById(request.getLearnerUserId())
                        .orElseThrow(() ->
                                new ResourceNotFoundException(
                                        "Learner user not found"
                                )
                        );

        validateUsers(
                exchangeRequest,
                teacher,
                learner
        );

        if (teacher.getId().equals(learner.getId())) {
            throw new BadRequestException(
                    "Teacher and learner cannot be the same user"
            );
        }

        /*
         * Only the teacher who owns this learning session
         * can schedule it.
         */
        if (!currentUser.getId().equals(teacher.getId())) {
            throw new BadRequestException(
                    "Only the teacher can schedule a learning session"
            );
        }

        if (request.getScheduledStart()
                .isBefore(LocalDateTime.now())) {

            throw new BadRequestException(
                    "Session start time must be in the future"
            );
        }

        if (sessionRepository.existsByExchangeRequestId(
                exchangeRequest.getId()
        )) {

            throw new BadRequestException(
                    "A session already exists for this exchange"
            );
        }

        LearningSession session =
                new LearningSession(
                        exchangeRequest,
                        teacher,
                        learner,
                        request.getTitle(),
                        request.getScheduledStart(),
                        request.getScheduledEnd()
                );

        session.setDescription(
                request.getDescription()
        );

        session.setSkillName(
                request.getSkillName()
        );

        session.setSessionType(
                request.getSessionType()
        );

        /*
         * Do NOT trust meetingUrl coming from frontend.
         *
         * The backend creates a unique learning-room token.
         * The frontend can use this route for the actual
         * learning-room/video implementation.
         */
        session.setMeetingUrl(
                generateMeetingUrl()
        );

        session.setLocation(
                request.getLocation()
        );

        session.setNotes(
                request.getNotes()
        );

        LearningSession saved =
                sessionRepository.save(session);

        return SessionResponse.from(saved);
    }

    @Transactional(readOnly = true)
    public SessionResponse getById(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        return SessionResponse.from(session);
    }

    @Transactional(readOnly = true)
    public List<SessionResponse> getMySessions(
            String userEmail
    ) {

        User user = getUser(userEmail);

        return sessionRepository
                .findMySessions(user.getId())
                .stream()
                .map(SessionResponse::from)
                .toList();
    }

    @Transactional(readOnly = true)
    public SessionPageResponse getMySessions(
            String userEmail,
            int page,
            int size
    ) {

        User user = getUser(userEmail);

        Pageable pageable =
                PageRequest.of(
                        normalizePage(page),
                        normalizeSize(size),
                        Sort.by(
                                Sort.Direction.ASC,
                                "scheduledStart"
                        )
                );

        Page<LearningSession> result =
                sessionRepository.findMySessions(
                        user.getId(),
                        pageable
                );

        return SessionPageResponse.from(result);
    }

    @Transactional(readOnly = true)
    public List<SessionResponse> getUpcomingSessions(
            String userEmail
    ) {

        User user = getUser(userEmail);

        List<SessionStatus> statuses =
                List.of(
                        SessionStatus.SCHEDULED,
                        SessionStatus.CONFIRMED,
                        SessionStatus.STARTED
                );

        return sessionRepository
                .findMyUpcomingSessions(
                        user.getId(),
                        statuses,
                        LocalDateTime.now()
                )
                .stream()
                .map(SessionResponse::from)
                .toList();
    }

    @Transactional(readOnly = true)
    public List<SessionResponse> getMySessionsByStatus(
            String userEmail,
            SessionStatus status
    ) {

        if (status == null) {
            throw new BadRequestException(
                    "Session status is required"
            );
        }

        User user = getUser(userEmail);

        return sessionRepository
                .findMySessionsByStatus(
                        user.getId(),
                        status
                )
                .stream()
                .map(SessionResponse::from)
                .toList();
    }

    @Transactional(readOnly = true)
    public SessionPageResponse getMySessionsByStatus(
            String userEmail,
            SessionStatus status,
            int page,
            int size
    ) {

        if (status == null) {
            throw new BadRequestException(
                    "Session status is required"
            );
        }

        User user = getUser(userEmail);

        Pageable pageable =
                PageRequest.of(
                        normalizePage(page),
                        normalizeSize(size),
                        Sort.by(
                                Sort.Direction.ASC,
                                "scheduledStart"
                        )
                );

        Page<LearningSession> result =
                sessionRepository.findMySessionsByStatus(
                        user.getId(),
                        status,
                        pageable
                );

        return SessionPageResponse.from(result);
    }

    @Transactional(readOnly = true)
    public List<SessionResponse> getSessionsByExchange(
            Long exchangeRequestId,
            String userEmail
    ) {

        if (exchangeRequestId == null) {
            throw new BadRequestException(
                    "Exchange request ID is required"
            );
        }

        LearningSession session =
                sessionRepository
                        .findFirstByExchangeRequestIdOrderByCreatedAtDesc(
                                exchangeRequestId
                        )
                        .orElseThrow(() ->
                                new ResourceNotFoundException(
                                        "Session not found for this exchange"
                                )
                        );

        User user = getUser(userEmail);

        validateParticipant(session, user);

        return sessionRepository
                .findByExchangeRequestId(exchangeRequestId)
                .stream()
                .map(SessionResponse::from)
                .toList();
    }

    public SessionResponse update(
            Long sessionId,
            UpdateSessionRequest request,
            String userEmail
    ) {

        if (request == null) {
            throw new BadRequestException(
                    "Update request is required"
            );
        }

        request.normalize();

        if (request.isEmpty()) {
            throw new BadRequestException(
                    "At least one field is required"
            );
        }

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        /*
         * Only the teacher can modify the scheduled
         * learning session.
         */
        if (!session.isTeacher(user.getId())) {
            throw new BadRequestException(
                    "Only the teacher can update the learning session"
            );
        }

        if (session.isClosed()) {
            throw new BadRequestException(
                    "Closed sessions cannot be updated"
            );
        }

        if (session.isStarted()) {
            throw new BadRequestException(
                    "Started sessions cannot be rescheduled"
            );
        }

        if (request.getTitle() != null) {
            session.setTitle(
                    request.getTitle()
            );
        }

        if (request.getDescription() != null) {
            session.setDescription(
                    request.getDescription()
            );
        }

        if (request.getSkillName() != null) {
            session.setSkillName(
                    request.getSkillName()
            );
        }

        if (request.getSessionType() != null) {
            session.setSessionType(
                    request.getSessionType()
            );
        }

        if (request.getScheduledStart() != null) {
            session.setScheduledStart(
                    request.getScheduledStart()
            );
        }

        if (request.getScheduledEnd() != null) {
            session.setScheduledEnd(
                    request.getScheduledEnd()
            );
        }

        if (request.hasScheduleUpdate()) {

            if (!session.hasValidSchedule()) {
                throw new BadRequestException(
                        "Scheduled end must be after scheduled start"
                );
            }

            if (session.getScheduledStart()
                    .isBefore(LocalDateTime.now())) {

                throw new BadRequestException(
                        "Scheduled start must be in the future"
                );
            }
        }

        /*
         * Meeting URL cannot be replaced by the frontend.
         * The original backend-generated URL remains unchanged.
         */

        if (request.getLocation() != null) {
            session.setLocation(
                    request.getLocation()
            );
        }

        if (request.getNotes() != null) {
            session.setNotes(
                    request.getNotes()
            );
        }

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse confirm(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isScheduled()) {
            throw new BadRequestException(
                    "Only scheduled sessions can be confirmed"
            );
        }

        session.confirm();

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse start(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isScheduled()
                && !session.isConfirmed()) {

            throw new BadRequestException(
                    "Session cannot be started in its current status"
            );
        }

        LocalDateTime now =
                LocalDateTime.now();

        if (session.getScheduledStart()
                .isAfter(now)) {

            throw new BadRequestException(
                    "Session start time has not arrived yet"
            );
        }

        if (!session.getScheduledEnd()
                .isAfter(now)) {

            throw new BadRequestException(
                    "Session time has already ended"
            );
        }

        session.start();

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse complete(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isStarted()) {
            throw new BadRequestException(
                    "Only started sessions can be completed"
            );
        }

        session.complete();

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse cancel(
            Long sessionId,
            String userEmail,
            String reason
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (session.isClosed()) {
            throw new BadRequestException(
                    "This session is already closed"
            );
        }

        if (session.isStarted()) {
            throw new BadRequestException(
                    "Started sessions cannot be cancelled"
            );
        }

        session.cancel(reason);

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse reject(
            Long sessionId,
            String userEmail,
            String reason
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isScheduled()
                && !session.isConfirmed()) {

            throw new BadRequestException(
                    "This session cannot be rejected"
            );
        }

        session.reject(reason);

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse markNoShow(
            Long sessionId,
            String userEmail,
            String reason
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isStarted()
                && !session.isConfirmed()
                && !session.isScheduled()) {

            throw new BadRequestException(
                    "This session cannot be marked as no-show"
            );
        }

        session.markNoShow(reason);

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public SessionResponse archive(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (!session.isClosed()) {
            throw new BadRequestException(
                    "Only closed sessions can be archived"
            );
        }

        session.archive();

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    /**
     * Marks the authenticated participant as joined.
     *
     * IMPORTANT:
     * The server checks the actual current time.
     *
     * Allowed:
     *     scheduledStart <= now < scheduledEnd
     *
     * Blocked:
     *     now < scheduledStart
     *     now >= scheduledEnd
     */
    public SessionResponse markJoined(
            Long sessionId,
            String userEmail
    ) {

        LearningSession session =
                getSession(sessionId);

        User user =
                getUser(userEmail);

        validateParticipant(
                session,
                user
        );

        if (session.isClosed()) {
            throw new BadRequestException(
                    "Closed sessions cannot be joined"
            );
        }

        LocalDateTime now =
                LocalDateTime.now();

        if (session.getScheduledStart() == null
                || session.getScheduledEnd() == null) {

            throw new BadRequestException(
                    "Session schedule is invalid"
            );
        }

        if (now.isBefore(
                session.getScheduledStart()
        )) {

            throw new BadRequestException(
                    "The learning session has not started yet"
            );
        }

        if (!now.isBefore(
                session.getScheduledEnd()
        )) {

            throw new BadRequestException(
                    "The learning session has ended"
            );
        }

        if (session.isTeacher(user.getId())) {

            session.markTeacherJoined();

        } else if (session.isLearner(user.getId())) {

            session.markLearnerJoined();

        } else {

            throw new BadRequestException(
                    "You are not a participant in this session"
            );
        }

        return SessionResponse.from(
                sessionRepository.save(session)
        );
    }

    public void expirePastSessions() {

        List<SessionStatus> statuses =
                List.of(
                        SessionStatus.SCHEDULED,
                        SessionStatus.CONFIRMED
                );

        List<LearningSession> sessions =
                sessionRepository.findSessionsPastEndTime(
                        statuses,
                        LocalDateTime.now()
                );

        for (LearningSession session : sessions) {
            session.expire();
        }

        if (!sessions.isEmpty()) {
            sessionRepository.saveAll(sessions);
        }
    }

    public long countMySessions(
            String userEmail
    ) {

        User user = getUser(userEmail);

        return sessionRepository
                .findMySessions(user.getId())
                .size();
    }

    public long countMySessionsByStatus(
            String userEmail,
            SessionStatus status
    ) {

        if (status == null) {
            throw new BadRequestException(
                    "Session status is required"
            );
        }

        User user = getUser(userEmail);

        return sessionRepository
                .countByTeacherUserAndStatus(
                        user,
                        status
                )
                +
                sessionRepository
                        .countByLearnerUserAndStatus(
                                user,
                                status
                        );
    }

    private LearningSession getSession(
            Long sessionId
    ) {

        if (sessionId == null) {
            throw new BadRequestException(
                    "Session ID is required"
            );
        }

        return sessionRepository
                .findById(sessionId)
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "Session not found"
                        )
                );
    }

    private User getUser(
            String email
    ) {

        if (email == null || email.isBlank()) {
            throw new BadRequestException(
                    "User email is required"
            );
        }

        String normalized =
                email.trim().toLowerCase();

        return userRepository
                .findByEmail(normalized)
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "User not found"
                        )
                );
    }

    private void validateParticipant(
            LearningSession session,
            User user
    ) {

        if (session == null || user == null) {
            throw new BadRequestException(
                    "Invalid session participant"
            );
        }

        if (!session.isParticipant(user.getId())) {
            throw new BadRequestException(
                    "You are not a participant in this session"
            );
        }
    }

    private void validateExchangeForSession(
            ExchangeRequest exchangeRequest,
            User currentUser
    ) {

        if (exchangeRequest == null) {
            throw new BadRequestException(
                    "Exchange request is required"
            );
        }

        if (exchangeRequest.getStatus()
                != ExchangeStatus.ACCEPTED) {

            throw new BadRequestException(
                    "Only accepted exchanges can create sessions"
            );
        }

        Long currentUserId =
                currentUser.getId();

        boolean participant =
                exchangeRequest
                        .getRequesterUser()
                        .getId()
                        .equals(currentUserId)
                ||
                exchangeRequest
                        .getRecipientUser()
                        .getId()
                        .equals(currentUserId);

        if (!participant) {
            throw new BadRequestException(
                    "You are not a participant in this exchange"
            );
        }
    }

    private void validateUsers(
            ExchangeRequest exchangeRequest,
            User teacher,
            User learner
    ) {

        Long requesterId =
                exchangeRequest
                        .getRequesterUser()
                        .getId();

        Long recipientId =
                exchangeRequest
                        .getRecipientUser()
                        .getId();

        boolean teacherParticipant =
                teacher.getId().equals(requesterId)
                        || teacher.getId().equals(recipientId);

        boolean learnerParticipant =
                learner.getId().equals(requesterId)
                        || learner.getId().equals(recipientId);

        if (!teacherParticipant
                || !learnerParticipant) {

            throw new BadRequestException(
                    "Teacher and learner must be participants in the exchange"
            );
        }
    }

    /**
     * Generates an internal unique learning-room URL.
     *
     * This URL is generated by the backend and cannot be
     * supplied/replaced by the frontend.
     *
     * The actual WebRTC/video-room implementation can use
     * this unique room token in the next phase.
     */
    private String generateMeetingUrl() {

        return "/learning-room/"
                + UUID.randomUUID();
    }

    private int normalizePage(int page) {

        return Math.max(page, 0);
    }

    private int normalizeSize(int size) {

        if (size < 1) {
            return 20;
        }

        return Math.min(size, 100);
    }
}