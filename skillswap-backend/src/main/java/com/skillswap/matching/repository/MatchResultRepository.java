package com.skillswap.matching.repository;

import com.skillswap.identity.entity.User;
import com.skillswap.matching.entity.MatchAlgorithm;
import com.skillswap.matching.entity.MatchResult;
import com.skillswap.matching.entity.MatchStatus;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;

/**
 * Repository for calculated matching results.
 *
 * The repository supports:
 *
 * - user-specific recommendations
 * - candidate lookups
 * - status filtering
 * - score ordering
 * - algorithm tracking
 * - pagination
 * - expiration handling
 * - viewed/unviewed recommendations
 *
 * No matching logic belongs here.
 * Matching/scoring decisions stay inside the service layer.
 */
public interface MatchResultRepository
        extends JpaRepository<MatchResult, Long> {

    /**
     * Finds a specific match by requester and candidate.
     */
    Optional<MatchResult>
    findByRequesterUserAndCandidateUser(
            User requesterUser,
            User candidateUser
    );

    /**
     * Finds a specific match by requester and candidate IDs.
     */
    Optional<MatchResult>
    findByRequesterUserIdAndCandidateUserId(
            Long requesterUserId,
            Long candidateUserId
    );

    /**
     * Checks whether a match already exists between two users.
     */
    boolean existsByRequesterUserAndCandidateUser(
            User requesterUser,
            User candidateUser
    );

    /**
     * Checks whether a match already exists by IDs.
     */
    boolean existsByRequesterUserIdAndCandidateUserId(
            Long requesterUserId,
            Long candidateUserId
    );

    /**
     * Returns all matches generated for a requester.
     */
    List<MatchResult>
    findAllByRequesterUserOrderByOverallScoreDesc(
            User requesterUser
    );

    /**
     * Returns all matches generated for a requester by User ID.
     */
    List<MatchResult>
    findAllByRequesterUserIdOrderByOverallScoreDesc(
            Long requesterUserId
    );

    /**
     * Returns paginated recommendations for a requester.
     */
    Page<MatchResult>
    findAllByRequesterUserIdOrderByOverallScoreDesc(
            Long requesterUserId,
            Pageable pageable
    );

    /**
     * Returns active/displayable-style statuses for a requester.
     *
     * The service can use this query as the base set and then
     * apply expiration rules when necessary.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndStatusInOrderByOverallScoreDesc(
            Long requesterUserId,
            List<MatchStatus> statuses
    );

    /**
     * Paginated status-filtered recommendations.
     */
    Page<MatchResult>
    findAllByRequesterUserIdAndStatusInOrderByOverallScoreDesc(
            Long requesterUserId,
            List<MatchStatus> statuses,
            Pageable pageable
    );

    /**
     * Finds matches above a minimum score.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndOverallScoreGreaterThanEqualOrderByOverallScoreDesc(
            Long requesterUserId,
            double minimumScore
    );

    /**
     * Finds matches above a minimum score with pagination.
     */
    Page<MatchResult>
    findAllByRequesterUserIdAndOverallScoreGreaterThanEqualOrderByOverallScoreDesc(
            Long requesterUserId,
            double minimumScore,
            Pageable pageable
    );

    /**
     * Finds matches that have not been viewed.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndViewedFalseOrderByOverallScoreDesc(
            Long requesterUserId
    );

    /**
     * Finds unviewed matches with pagination.
     */
    Page<MatchResult>
    findAllByRequesterUserIdAndViewedFalseOrderByOverallScoreDesc(
            Long requesterUserId,
            Pageable pageable
    );

    /**
     * Finds matches that have already been viewed.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndViewedTrueOrderByOverallScoreDesc(
            Long requesterUserId
    );

    /**
     * Finds matches by status.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndStatusOrderByOverallScoreDesc(
            Long requesterUserId,
            MatchStatus status
    );

    /**
     * Finds paginated matches by status.
     */
    Page<MatchResult>
    findAllByRequesterUserIdAndStatusOrderByOverallScoreDesc(
            Long requesterUserId,
            MatchStatus status,
            Pageable pageable
    );

    /**
     * Finds matches generated by a specific algorithm.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndAlgorithmOrderByOverallScoreDesc(
            Long requesterUserId,
            MatchAlgorithm algorithm
    );

    /**
     * Finds all matches where a specific user is the candidate.
     */
    List<MatchResult>
    findAllByCandidateUserIdOrderByOverallScoreDesc(
            Long candidateUserId
    );

    /**
     * Finds matches where the user is either requester or candidate.
     *
     * This is useful later for a user's complete matching history.
     */
    List<MatchResult>
    findAllByRequesterUserIdOrCandidateUserIdOrderByGeneratedAtDesc(
            Long requesterUserId,
            Long candidateUserId
    );

    /**
     * Finds matches generated before a specific time.
     */
    List<MatchResult>
    findAllByGeneratedAtBefore(
            LocalDateTime before
    );

    /**
     * Finds matches that have expired according to expiresAt.
     */
    List<MatchResult>
    findAllByExpiresAtBefore(
            LocalDateTime before
    );

    /**
     * Finds matches whose expiration timestamp is still in the future.
     */
    List<MatchResult>
    findAllByExpiresAtAfter(
            LocalDateTime after
    );

    /**
     * Finds expired matches for a particular requester.
     */
    List<MatchResult>
    findAllByRequesterUserIdAndExpiresAtBefore(
            Long requesterUserId,
            LocalDateTime before
    );

    /**
     * Counts all matches generated for a requester.
     */
    long countByRequesterUserId(Long requesterUserId);

    /**
     * Counts matches by requester and status.
     */
    long countByRequesterUserIdAndStatus(
            Long requesterUserId,
            MatchStatus status
    );

    /**
     * Counts matches above a specific score.
     */
    long countByRequesterUserIdAndOverallScoreGreaterThanEqual(
            Long requesterUserId,
            double minimumScore
    );

    /**
     * Counts unviewed matches.
     */
    long countByRequesterUserIdAndViewedFalse(
            Long requesterUserId
    );

    /**
     * Counts viewed matches.
     */
    long countByRequesterUserIdAndViewedTrue(
            Long requesterUserId
    );

    /**
     * Counts matches using a specific algorithm.
     */
    long countByAlgorithm(
            MatchAlgorithm algorithm
    );

    /**
     * Counts matches with a specific status.
     */
    long countByStatus(
            MatchStatus status
    );

    /**
     * Counts all matches generated after a timestamp.
     */
    long countByGeneratedAtAfter(
            LocalDateTime after
    );

    /**
     * Deletes all match results involving a user as requester.
     */
    void deleteAllByRequesterUser(User user);

    /**
     * Deletes all match results involving a user as candidate.
     */
    void deleteAllByCandidateUser(User user);

    /**
     * Deletes all matches involving a user by ID.
     */
    void deleteAllByRequesterUserId(Long userId);

    /**
     * Deletes all matches where a user is a candidate by ID.
     */
    void deleteAllByCandidateUserId(Long userId);
}