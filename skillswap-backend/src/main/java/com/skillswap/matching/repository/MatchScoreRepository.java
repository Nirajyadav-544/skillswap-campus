package com.skillswap.matching.repository;

import com.skillswap.matching.entity.MatchAlgorithm;
import com.skillswap.matching.entity.MatchScore;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;
import java.util.Optional;

/**
 * Repository for detailed MatchScore persistence and retrieval.
 *
 * MatchScore contains the component-level breakdown of a MatchResult.
 *
 * The repository is intentionally focused only on persistence.
 * Score calculation belongs to MatchScoreService / MatchingService.
 */
public interface MatchScoreRepository
        extends JpaRepository<MatchScore, Long> {

    /**
     * Finds the score belonging to a particular MatchResult.
     *
     * MatchScore has a one-to-one relationship with MatchResult.
     */
    Optional<MatchScore> findByMatchResultId(Long matchResultId);

    /**
     * Checks whether a score already exists for a match result.
     */
    boolean existsByMatchResultId(Long matchResultId);

    /**
     * Finds all scores generated by a particular algorithm.
     */
    List<MatchScore> findAllByAlgorithm(
            MatchAlgorithm algorithm
    );

    /**
     * Finds all scores generated by a particular algorithm,
     * ordered from highest to lowest overall score.
     */
    List<MatchScore>
    findAllByAlgorithmOrderByOverallScoreDesc(
            MatchAlgorithm algorithm
    );

    /**
     * Finds paginated scores for an algorithm.
     */
    Page<MatchScore>
    findAllByAlgorithmOrderByOverallScoreDesc(
            MatchAlgorithm algorithm,
            Pageable pageable
    );

    /**
     * Finds scores above a minimum overall score.
     */
    List<MatchScore>
    findAllByOverallScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumScore
    );

    /**
     * Finds high-quality scores using pagination.
     */
    Page<MatchScore>
    findAllByOverallScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumScore,
            Pageable pageable
    );

    /**
     * Finds scores with at least a certain number of matching skills.
     */
    List<MatchScore>
    findAllByMatchingSkillCountGreaterThanEqualOrderByOverallScoreDesc(
            int minimumMatchingSkills
    );

    /**
     * Finds scores with strong skill compatibility.
     */
    List<MatchScore>
    findAllBySkillScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumSkillScore
    );

    /**
     * Finds scores with strong proficiency compatibility.
     */
    List<MatchScore>
    findAllByProficiencyScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumProficiencyScore
    );

    /**
     * Finds scores with strong experience compatibility.
     */
    List<MatchScore>
    findAllByExperienceScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumExperienceScore
    );

    /**
     * Finds scores with strong profile compatibility.
     */
    List<MatchScore>
    findAllByProfileScoreGreaterThanEqualOrderByOverallScoreDesc(
            double minimumProfileScore
    );

    /**
     * Finds the strongest scores.
     */
    List<MatchScore>
    findTop20ByOrderByOverallScoreDesc();

    /**
     * Finds the strongest skill-compatible scores.
     */
    List<MatchScore>
    findTop20ByOrderBySkillScoreDesc();

    /**
     * Counts scores using an algorithm.
     */
    long countByAlgorithm(
            MatchAlgorithm algorithm
    );

    /**
     * Counts scores above a minimum score.
     */
    long countByOverallScoreGreaterThanEqual(
            double minimumScore
    );

    /**
     * Counts scores containing matching skills.
     */
    long countByMatchingSkillCountGreaterThanEqual(
            int minimumMatchingSkills
    );

    /**
     * Deletes the score belonging to a MatchResult.
     */
    void deleteByMatchResultId(Long matchResultId);

    /**
     * Deletes all scores belonging to a collection of match results.
     *
     * This method can be used later by cleanup services.
     */
    void deleteAllByMatchResultIdIn(
            List<Long> matchResultIds
    );
}